import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const [dictionaryPath, affixPath, outputPath = "shared/wordle-pt-br-lexicon.generated.ts"] = process.argv.slice(2);
if (!dictionaryPath || !affixPath) {
  throw new Error("usage: node scripts/generate-wordle-pt-br-lexicon.mjs <pt_BR.dic> <pt_BR.aff> [output]");
}

const [dictionarySource, affixSource] = await Promise.all([
  readFile(dictionaryPath, "utf8"),
  readFile(affixPath, "utf8"),
]);

const normalize = value => value.normalize("NFD").replace(/\p{Diacritic}/gu, "").toUpperCase();
const accepted = value => /^[A-Z]{5,7}$/.test(value);
const rules = new Map();

for (const rawLine of affixSource.split(/\r?\n/)) {
  const line = rawLine.trim();
  if (!/^(PFX|SFX)\s/.test(line)) continue;
  const parts = line.split(/\s+/);
  if (parts.length === 4 && /^\d+$/.test(parts[3])) {
    rules.set(`${parts[0]}:${parts[1]}`, { kind: parts[0], cross: parts[2] === "Y", entries: [] });
    continue;
  }
  if (parts.length < 5) continue;
  const rule = rules.get(`${parts[0]}:${parts[1]}`);
  if (!rule) continue;
  const [addition, continuation = ""] = parts[3].split("/");
  rule.entries.push({
    strip: parts[2] === "0" ? "" : parts[2],
    addition: addition === "0" ? "" : addition,
    continuation,
    condition: parts[4],
  });
}

function applyRule(word, rule, entry) {
  try {
    const matches = rule.kind === "PFX"
      ? new RegExp(`^(?:${entry.condition})`, "u").test(word)
      : new RegExp(`(?:${entry.condition})$`, "u").test(word);
    if (!matches) return null;
    if (rule.kind === "PFX") {
      if (entry.strip && !word.startsWith(entry.strip)) return null;
      return entry.addition + word.slice(entry.strip.length);
    }
    if (entry.strip && !word.endsWith(entry.strip)) return null;
    return word.slice(0, entry.strip ? -entry.strip.length : undefined) + entry.addition;
  } catch {
    return null;
  }
}

const words = new Set();
const dictionaryLines = dictionarySource.split(/\r?\n/).slice(1);
for (const rawLine of dictionaryLines) {
  const token = rawLine.trim().split(/\s+/)[0];
  if (!token) continue;
  const slash = token.indexOf("/");
  const root = (slash < 0 ? token : token.slice(0, slash)).replaceAll("\\/", "/");
  const flags = slash < 0 ? "" : token.slice(slash + 1);
  const normalizedRoot = normalize(root);
  if (accepted(normalizedRoot)) words.add(normalizedRoot);

  const prefixRules = [...flags].map(flag => rules.get(`PFX:${flag}`)).filter(Boolean);
  const suffixRules = [...flags].map(flag => rules.get(`SFX:${flag}`)).filter(Boolean);
  const prefixed = [];
  const suffixed = [];
  for (const rule of prefixRules) for (const entry of rule.entries) {
    const result = applyRule(root, rule, entry);
    if (result) prefixed.push({ word: result, rule });
  }
  for (const rule of suffixRules) for (const entry of rule.entries) {
    const result = applyRule(root, rule, entry);
    if (result) suffixed.push({ word: result, rule });
  }
  for (const result of [...prefixed, ...suffixed]) {
    const normalized = normalize(result.word);
    if (accepted(normalized)) words.add(normalized);
  }
  for (const prefix of prefixed.filter(item => item.rule.cross)) {
    for (const suffixRule of suffixRules.filter(rule => rule.cross)) {
      for (const entry of suffixRule.entries) {
        const result = applyRule(prefix.word, suffixRule, entry);
        if (result) {
          const normalized = normalize(result);
          if (accepted(normalized)) words.add(normalized);
        }
      }
    }
  }
}

const sorted = [...words].sort();
const lines = [];
for (let index = 0; index < sorted.length; index += 24) lines.push(sorted.slice(index, index + 24).join(" "));
const dictionarySha256 = createHash("sha256").update(dictionarySource).digest("hex");
const affixSha256 = createHash("sha256").update(affixSource).digest("hex");
const generated = `// Generated by scripts/generate-wordle-pt-br-lexicon.mjs. Do not edit manually.
// Source: LibreOffice dictionaries pt_BR @ f2ff99058268502bdcf4cad25c1ca2935ad8aa7d
// License: LGPL-3.0-or-later / Mozilla Public License, as declared by the source.
// pt_BR.dic SHA-256: ${dictionarySha256}
// pt_BR.aff SHA-256: ${affixSha256}
export const WORDLE_PT_BR_WORDS = new Set(\`
${lines.join("\n")}
\`.trim().split(/\\s+/));

export const WORDLE_PT_BR_WORD_COUNT = ${sorted.length};
`;
await writeFile(path.resolve(outputPath), generated, "utf8");
console.log(`Generated ${sorted.length} normalized Wordle guesses at ${outputPath}.`);
